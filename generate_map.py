"""
关卡地图生成器 v2 — 更多尖刺、纵向攀升、窄路径
"""
COLS = 600
ROWS = 13
G = [['.' for _ in range(COLS)] for _ in range(ROWS)]
for c in range(COLS):
    G[11][c] = '1'; G[12][c] = '2'

def p(r,c,ch):        # 单点
    if 0<=r<ROWS and 0<=c<COLS: G[r][c]=ch
def ph(r,cs,ce,ch):    # 水平线
    for c in range(max(0,cs), min(ce+1,COLS)): p(r,c,ch)
def pr(rt,rb,cl,cr,ch): # 矩形
    for r in range(rt,rb+1):
        for c in range(cl,cr+1): p(r,c,ch)
def plat(rt,cl,cr):    # 浮台(2格厚草+土)
    ph(rt,cl,cr,'1'); ph(rt+1,cl,cr,'2')
def water(r,cs,ce):    # 水域
    ph(r,cs,ce,'3'); ph(r+1,cs,ce,'4')
def hole(cs,ce):       # 挖掉行11草地
    for c in range(cs,ce+1):
        if G[11][c]=='1': G[11][c]='.'
def path(cs,ce,w=99,r=11): # 在行r铺w格宽的草地
    if w==99: w=ce-cs+1
    mid = (cs+ce)//2; hw=w//2
    hole(cs,ce)
    for c in range(max(cs,mid-hw+(1 if w%2==0 else 0)), min(ce+1,mid+hw+1)):
        if r==11: G[11][c]='1'
        else: p(r,c,'1')
def spike(c,row=10,typ='7'): p(row,c,typ)
def spikes(cs,ce,row=10,typ='7',step=2):
    for c in range(cs,ce+1,step): spike(c,row,typ)
def enemy(r,c,typ): p(r,c,typ)  # r=行, c=列

